BindingModel analyzeModuleBindings(const BindingGenerationOptions& options) {
    const auto selected = loadModuleManifest(options.moduleDirectory);
    const auto dependencies = dependencyManifests(options, selected);
    Runtime runtime;
    if (!dependencies.empty()) {
        requireCompilation(loadSourceRoots(getModuleScriptRoots(dependencies)), runtime);
    }
    std::vector<const Type*> existing;
    runtime.getTypes(existing);
    const std::set<const Type*> dependencyTypes(existing.begin(), existing.end());
    const auto sources = loadSourceRoots(getModuleScriptRoots(std::vector{selected}));
    if (sources.sources.empty() && sources.diagnostics.empty()) {
        generatorError("selected module has no script sources");
    }
    requireCompilation(sources, runtime);
    std::vector<const Type*> types;
    runtime.getTypes(types);
    BindingModel model{selected.name, {}, {}};
    std::set<NomadString> enumNames;
    for (const auto* type : types) {
        if (dependencyTypes.contains(type)) {
            continue;
        }
        if (const auto* enumeration = type->asEnum()) {
            model.enums.push_back(describeEnum(*enumeration));
            enumNames.insert(enumeration->getTypeName());
        } else if (const auto* classType = type->asClassType()) {
            const auto constructors = classType->getConstructors();
            if (!classType->getTypeArguments().empty() || !classType->getMethods().empty() ||
                !classType->getNativeIndexers().empty() || classType->getIterableInfo() ||
                constructors.size() != 1 || constructors.front()->asScriptConstructor() == nullptr ||
                constructors.front()->getParameterCount() != 0) {
                generatorError("unsupported class shape '" + classType->getTypeName() +
                    "' (expected stored fields and one zero-argument script constructor)");
            }
            BindingClass description{classType->getTypeName(), {}, {}};
            for (const auto* property : classType->getProperties()) {
                const auto* fieldType = property->getValueType();
                if (property->asNativeProperty() != nullptr || fieldType == nullptr ||
                    (!isPrimitive(fieldType->getTypeName()) && fieldType->asEnum() == nullptr)) {
                    generatorError("unsupported stored field '" + classType->getTypeName() + "." +
                        property->getName() + "'");
                }
                description.fields.push_back({property->getName(), fieldType->getTypeName()});
                if (const auto* fieldEnumeration = fieldType->asEnum()) {
                    if (std::ranges::none_of(description.enums, [&](const auto& entry) {
                        return entry.name == fieldEnumeration->getTypeName();
                    })) {
                        description.enums.push_back(describeEnum(*fieldEnumeration));
                    }
                }
            }
            std::ranges::sort(description.fields, {}, &BindingField::name);
            std::ranges::sort(description.enums, {}, &BindingEnum::name);
            model.classes.push_back(std::move(description));
        } else {
            generatorError("unsupported declaration type '" + type->getTypeName() + "'");
        }
    }
    // A selected class may use an enum from a script dependency.
    for (const auto& classType : model.classes) {
        for (const auto& enumeration : classType.enums) {
            if (enumNames.insert(enumeration.name).second) {
                model.enums.push_back(enumeration);
            }
        }
    }
    if (model.enums.empty() && model.classes.empty()) {
        generatorError("selected module declares no supported enums or configuration classes");
    }
    std::ranges::sort(model.enums, {}, &BindingEnum::name);
    std::ranges::sort(model.classes, {}, &BindingClass::name);
    validateModel(model);
    return model;
}

std::vector<BindingOutput> renderModuleBindings(const BindingModel& model) {
    validateModel(model);
    const auto moduleNamespace = identifier(model.module, '-');
    const auto includePath = "nomad/generated/" + model.module + "/Bindings.hpp";
    const auto scope = "nomad::generated::" + moduleNamespace;
    std::ostringstream header;
    std::ostringstream source;
    header << "// " << generatedMarker << "\n\n#pragma once\n\n"
        "#include <nomad/script/ScriptBindingObject.hpp>\n\nnamespace " << scope << " {\n\n";
    source << "// " << generatedMarker << "\n\n#include <" << includePath << ">\n\n"
        "#include <utility>\n\nnamespace " << scope << " {\n\n";
    for (const auto& enumeration : model.enums) {
        header << "enum class " << typeIdentifier(enumeration.name) << " : nomad::NomadInteger {\n";
        for (const auto& value : enumeration.values) {
            header << "    " << value.name << " = " << integerLiteral(value.value) << ",\n";
        }
        header << "};\n\n";
    }
    for (auto index = NomadIndex{0}; index < model.classes.size(); ++index) {
        const auto& classType = model.classes[index];
        const auto name = typeIdentifier(classType.name);
        const auto contractName = "contract" + std::to_string(index);
        source << "namespace {\n\nconst nomad::BindingClass& " << contractName << "() {\n"
            "    static const nomad::BindingClass contract{\n        \"" << classType.name << "\",\n        {\n";
        for (const auto& field : classType.fields) {
            source << "            {\"" << field.name << "\", \"" << field.type << "\"},\n";
        }
        source << "        },\n        {\n";
        for (const auto& enumeration : classType.enums) {
            writeEnumContract(source, enumeration);
        }
        source << "        }\n    };\n    return contract;\n}\n\n} // namespace\n\n";
        header << "class " << name << " final {\npublic:\n"
            "    " << name << "(nomad::Runtime& runtime, nomad::NomadObject* object);\n"
            "    [[nodiscard]] static " << name << " create(nomad::Runtime& runtime, nomad::VirtualMachine& machine);\n"
            "    [[nodiscard]] nomad::NomadObject* getObject() const;\n"
            "    [[nodiscard]] nomad::Runtime& getRuntime() const;\n";
        source << name << "::" << name << "(nomad::Runtime& runtime, nomad::NomadObject* object) :\n"
            "    m_binding(runtime, object, " << contractName << "()) {\n}\n\n"
            << name << "::" << name << "(nomad::ScriptBindingObject binding) : m_binding(std::move(binding)) {\n}\n\n"
            << name << " " << name << "::create(nomad::Runtime& runtime, nomad::VirtualMachine& machine) {\n"
            "    return " << name << "(nomad::ScriptBindingObject::construct(runtime, machine, " << contractName << "()));\n}\n\n"
            "nomad::NomadObject* " << name << "::getObject() const {\n    return m_binding.getObject();\n}\n\n"
            "nomad::Runtime& " << name << "::getRuntime() const {\n    return m_binding.getRuntime();\n}\n\n";
        for (const auto& field : classType.fields) {
            const auto fieldCppType = cppType(field.type);
            const auto suffix = accessorSuffix(field.name);
            const auto argument = field.type == STRING_TYPE_NAME ? "const " + fieldCppType + "&" : fieldCppType;
            header << "    [[nodiscard]] " << fieldCppType << " get" << suffix << "() const;\n"
                "    void set" << suffix << "(" << argument << " value);\n";
            source << fieldCppType << " " << name << "::get" << suffix << "() const {\n    return ";
            if (!isPrimitive(field.type)) {
                source << "static_cast<" << fieldCppType << ">(";
            }
            source << "m_binding.get" << valueKind(field.type) << "(\"" << field.name << "\")";
            if (!isPrimitive(field.type)) {
                source << ")";
            }
            source << ";\n}\n\nvoid " << name << "::set" << suffix << "(" << argument << " value) {\n"
                "    m_binding.set" << valueKind(field.type) << "(\"" << field.name << "\", ";
            source << (isPrimitive(field.type) ? "value" : "static_cast<nomad::NomadInteger>(value)") << ");\n}\n\n";
        }
        header << "\nprivate:\n    explicit " << name << "(nomad::ScriptBindingObject binding);\n"
            "    nomad::ScriptBindingObject m_binding;\n};\n\n";
    }
    header << "} // namespace " << scope << "\n";
    source << "} // namespace " << scope << "\n";
    const auto inventory = NomadString("# ") + generatedMarker +
        "\n# Include explicitly from a consuming target; this file never runs the generator.\n"
        "set(NOMAD_BINDING_INCLUDE_DIRECTORY \"${CMAKE_CURRENT_LIST_DIR}/include\")\n"
        "set(NOMAD_BINDING_HEADERS \"${CMAKE_CURRENT_LIST_DIR}/include/" + includePath + "\")\n"
        "set(NOMAD_BINDING_SOURCES \"${CMAKE_CURRENT_LIST_DIR}/src/Bindings.cpp\")\n";
    return {{pathFromUtf8("include/" + includePath), header.str()},
        {NomadPath("src") / "Bindings.cpp", source.str()}, {"nomad-module.cmake", inventory}};
}

