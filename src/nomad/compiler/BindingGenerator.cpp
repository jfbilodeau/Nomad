constexpr auto generatedMarker = "Generated by nomad generate-bindings. Do not edit.";

[[noreturn]] void generatorError(const NomadString& message) {
    throw NomadException("Binding generation: " + message);
}

NomadString identifier(NomadString name, char separator) {
    std::ranges::replace(name, separator, '_');
    static const std::set<NomadString> keywords{
        "alignas", "alignof", "and", "and_eq", "asm", "auto", "bitand", "bitor", "bool", "break",
        "case", "catch", "char", "char8_t", "char16_t", "char32_t", "class", "compl", "concept",
        "const", "consteval", "constexpr", "constinit", "const_cast", "continue", "co_await", "co_return",
        "co_yield", "decltype", "default", "delete", "do", "double", "dynamic_cast", "else", "enum",
        "explicit", "export", "extern", "false", "float", "for", "friend", "goto", "if", "inline", "int",
        "long", "mutable", "namespace", "new", "noexcept", "not", "not_eq", "nullptr", "operator", "or",
        "or_eq", "private", "protected", "public", "register", "reinterpret_cast", "requires", "return",
        "short", "signed", "sizeof", "static", "static_assert", "static_cast", "struct", "switch",
        "template", "this", "thread_local", "throw", "true", "try", "typedef", "typeid", "typename",
        "union", "unsigned", "using", "virtual", "void", "volatile", "wchar_t", "while", "xor", "xor_eq"
    };
    const auto letter = [](char character) {
        return (character >= 'a' && character <= 'z') || (character >= 'A' && character <= 'Z');
    };
    if (name.empty() || !letter(name.front()) || name.find("__") != NomadString::npos ||
        !std::ranges::all_of(name, [&](char character) {
            return letter(character) || (character >= '0' && character <= '9') || character == '_';
        }) || keywords.contains(name)) {
        generatorError("unsupported or reserved C++ name '" + name + "'");
    }
    return name;
}

NomadString typeIdentifier(const NomadString& name) {
    // Validate every component as well as the flattened name.
    auto start = NomadIndex{0};
    do {
        const auto end = name.find('.', start);
        (void)identifier(name.substr(start, end == NomadString::npos ? end : end - start), '.');
        if (end == NomadString::npos) {
            break;
        }
        start = end + 1;
    } while (true);
    return identifier(name, '.');
}

NomadString accessorSuffix(const NomadString& name) {
    auto result = identifier(name, '.');
    if (result.front() >= 'a' && result.front() <= 'z') {
        result.front() = static_cast<char>(result.front() - 'a' + 'A');
    }
    return result;
}

void requireCompilation(const SourceBatch& batch, Runtime& runtime) {
    const auto result = checkSources(batch, &runtime);
    if (!result.succeeded()) {
        NomadString message = "script compilation failed (native modules are not loaded)";
        for (const auto& diagnostic : result.diagnostics) {
            message += "\n" + formatDiagnostic(diagnostic);
        }
        generatorError(message);
    }
}

BindingEnum describeEnum(const EnumType& type) {
    BindingEnum result{type.getTypeName(), {}};
    for (auto index = NomadIndex{0}; index < type.getValueCount(); ++index) {
        result.values.push_back(type.getValue(index));
    }
    return result;
}

NomadString cppType(const NomadString& name) {
    if (name == BOOLEAN_TYPE_NAME) {
        return "nomad::NomadBoolean";
    }
    if (name == INTEGER_TYPE_NAME) {
        return "nomad::NomadInteger";
    }
    if (name == FLOAT_TYPE_NAME) {
        return "nomad::NomadFloat";
    }
    if (name == STRING_TYPE_NAME) {
        return "nomad::NomadString";
    }
    return typeIdentifier(name);
}

NomadString valueKind(const NomadString& name) {
    if (name == BOOLEAN_TYPE_NAME) {
        return "Boolean";
    }
    if (name == FLOAT_TYPE_NAME) {
        return "Float";
    }
    if (name == STRING_TYPE_NAME) {
        return "String";
    }
    return "Integer";
}

bool isPrimitive(const NomadString& name) {
    return name == BOOLEAN_TYPE_NAME || name == INTEGER_TYPE_NAME ||
        name == FLOAT_TYPE_NAME || name == STRING_TYPE_NAME;
}

void validateModel(const BindingModel& model) {
    const auto moduleNamespace = identifier(model.module, '-');
    if (moduleNamespace == "nomad" || moduleNamespace == "std") {
        generatorError("C++ namespace name collision: '" + moduleNamespace + "'");
    }
    std::set<NomadString> names;
    // Avoid hiding the library namespace used in all generated signatures.
    names.insert("nomad");
    names.insert("std");
    for (auto index = NomadIndex{0}; index < model.classes.size(); ++index) {
        names.insert("contract" + std::to_string(index));
    }
    std::set<NomadString> typeNames;
    for (const auto& enumeration : model.enums) {
        typeNames.insert(typeIdentifier(enumeration.name));
    }
    for (const auto& classType : model.classes) {
        typeNames.insert(typeIdentifier(classType.name));
    }
    for (const auto& enumeration : model.enums) {
        const auto name = typeIdentifier(enumeration.name);
        if (!names.insert(name).second) {
            generatorError("C++ type name collision: '" + name + "'");
        }
        std::set<NomadString> values{name};
        for (const auto& value : enumeration.values) {
            if (!values.insert(identifier(value.name, '.')).second) {
                generatorError("C++ enum name collision in '" + enumeration.name + "'");
            }
        }
    }
    for (const auto& classType : model.classes) {
        const auto name = typeIdentifier(classType.name);
        if (!names.insert(name).second) {
            generatorError("C++ type name collision: '" + name + "'");
        }
        if (name == "create" || name == "getObject" || name == "getRuntime" || name == "m_binding") {
            generatorError("C++ binding member name collision: '" + name + "'");
        }
        std::set<NomadString> members{name, "create", "getObject", "getRuntime", "m_binding"};
        for (const auto& field : classType.fields) {
            const auto suffix = accessorSuffix(field.name);
            if (typeNames.contains("get" + suffix) || typeNames.contains("set" + suffix) ||
                !members.insert("get" + suffix).second || !members.insert("set" + suffix).second) {
                generatorError("C++ accessor name collision in '" + classType.name + "." + field.name + "'");
            }
            if (!isPrimitive(field.type) && std::ranges::none_of(model.enums, [&](const auto& enumeration) {
                return enumeration.name == field.type;
            })) {
                generatorError("unsupported field type '" + field.type + "'");
            }
        }
    }
}

NomadString integerLiteral(NomadInteger value) {
    if (value == std::numeric_limits<NomadInteger>::min()) {
        return "(-9223372036854775807LL - 1)";
    }
    return std::to_string(value) + "LL";
}

void writeEnumContract(std::ostream& output, const BindingEnum& enumeration) {
    output << "            {\"" << enumeration.name << "\", {";
    for (const auto& value : enumeration.values) {
        output << "{\"" << value.name << "\", " << integerLiteral(value.value) << "}, ";
    }
    output << "}},\n";
}

NomadString readFile(const NomadPath& path) {
    std::ifstream input(path, std::ios::binary);
    if (!input) {
        generatorError("cannot read '" + pathToUtf8(path) + "'");
    }
    NomadString result{std::istreambuf_iterator<char>(input), std::istreambuf_iterator<char>()};
    if (input.bad()) {
        generatorError("cannot read '" + pathToUtf8(path) + "'");
    }
    return result;
}

bool overlaps(const NomadPath& first, const NomadPath& second) {
    return getSourceRelativePath(first, second).has_value() || getSourceRelativePath(second, first).has_value();
}

std::vector<ModuleManifest> dependencyManifests(
    const BindingGenerationOptions& options,
    const ModuleManifest& selected
) {
    if (selected.dependencies.empty()) {
        return {};
    }
    if (!options.sdkDirectory) {
        generatorError("module dependencies require an explicit --sdk directory");
    }
    auto result = resolveModules(*options.sdkDirectory / "modules", selected.dependencies);
    if (std::ranges::any_of(result, [&](const auto& dependency) { return dependency.name == selected.name; })) {
        generatorError("dependency graph refers back to the selected module");
    }
    return result;
}

